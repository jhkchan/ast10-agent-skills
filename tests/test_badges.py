def test_the_judged_badge_matches_a_recompute_over_the_scorecards():
    shipped, roster, pooled_mean, pooled_n = _judged()
    committed = badge("judged")
    assert committed.message == f"{shipped}/{roster} SHIP {DOT} {pooled_mean:g}/120 {DOT} {_panel_size()}-model panel"
    assert committed.link == "docs/skill-judge-dashboard.md"
    assert str(pooled_n) in committed.alt, (
        "the alt text quotes the pooled n; a mean with no n is not a published statistic"
    )
    dashboard = (REPO_ROOT / "docs" / "skill-judge-dashboard.md").read_text(encoding="utf-8")
    assert f"{pooled_mean:g}" in dashboard, "the badge and the dashboard it links disagree about the pooled mean"
    provenance = (REPO_ROOT / "vendor" / "skill-judge" / "PROVENANCE.md").read_text(encoding="utf-8")
    assert "120 points" in provenance, "the badge's /120 denominator must come from the vendored rubric's own record"


def test_the_detector_f1_badge_matches_the_committed_f1_report():
    buckets = _f1_categories()
    published, below_floor, publish_none = (
        buckets["pass"],
        buckets["fail"],
        buckets["declared-and-uncovered"],
    )
    total = len(published) + len(below_floor) + len(publish_none)
    assert not below_floor, "a category now falls below the F1 floor; the badge must say so rather than reading clean"
    committed = badge("detector F1")
    assert committed.message == f"{_f1_published_score():.3f} {DOT} where a package can decide it"
    assert f"{len(published)} of {total}" in committed.alt, (
        f"the coverage count left the pill; the row must still publish it: {committed.alt!r}"
    )
    assert f"{len(publish_none)} publish none by rule" in committed.alt, (
        f"the count of categories that publish none left the row entirely: {committed.alt!r}"
    )
    assert committed.link == "docs/f1-report.md"
    for row in published:
        assert row["scenario_level"] and row["scenario_level"]["f1"] is not None, (
            f"{row['category']} is counted as publishing an F1 but has no scenario-level number"
        )


def test_the_output_eval_badge_matches_the_blind_control_arm():
    delta, with_rate, without_rate, n = _control_delta()
    committed = badge("output eval")
    assert committed.message == f"{with_rate:.2f} with {DOT} {without_rate:.2f} without"
    assert committed.link == "docs/skill-eval-report.md"
    assert str(n) in committed.alt, "the alt text quotes the control n"
    assert f"+{delta:.2f}" in committed.alt, (
        f"the measured delta left the pill; the row must still publish it: {committed.alt!r}"
    )


def test_the_output_eval_badge_is_the_control_arm_and_not_the_whole_corpus():
    """The whole-corpus arms are different, larger-n numbers. Publishing any of them
    under the words 'blind control' would badge a measurement nobody made.

    The row now shows two arms on the pill and the delta in the alt, so all three
    are checked against their whole-corpus look-alikes rather than the delta alone.
    """
    payload = json.loads(
        (REPO_ROOT / "eval" / "skill-eval-workspace" / "iteration-3" / "benchmark.json").read_text(encoding="utf-8")
    )
    summary = payload["run_summary"]
    corpus_delta = round(float(summary["delta"]["pass_rate"]), 2)
    corpus_with = round(float(summary["with_skill"]["pass_rate"]["mean"]), 2)
    corpus_without = round(float(summary["without_skill"]["pass_rate"]["mean"]), 2)
    control_delta, control_with, control_without, _n = _control_delta()
    committed = badge("output eval")
    assert f"{control_with:.2f} with" in committed.message
    assert f"{control_without:.2f} without" in committed.message
    assert f"+{control_delta:.2f}" in committed.alt
    if corpus_with != control_with:
        assert f"{corpus_with:.2f} with" not in committed.message, "the pill shows the whole-corpus with-arm"
    if corpus_without != control_without:
        assert f"{corpus_without:.2f} without" not in committed.message, "the pill shows the whole-corpus without-arm"
    if corpus_delta != control_delta:
        assert f"+{corpus_delta:.2f}" not in committed.alt, "the row quotes the whole-corpus delta as the control's"


