"""The badge row as a PUBLISHED FIGURE — re-derived from source, not from its generator.

This repository drift-guards every published figure, because the alternative has
bitten it four times: a dashboard banner that said no judged run existed while
four scorecards sat in the tree, run-2 figures surviving into run 3, an ``n=33``
that had become 32, and a README claiming there were no scorecards. A badge is
the most-read figure on the page and the least likely to be re-checked by hand,
so it is the figure most worth guarding.

**Why this file exists beside ``tests/test_generate_badges.py``.** That file is
the generator's unit test: it imports ``scripts.generate_badges``, monkeypatches
its derivations, and drives its caveat states. Necessary, but it cannot close the
loop on its own — it reads the expected separator, marker and colour constants
out of the very module it is checking, so a literal that was wrong *inside* the
generator would be confirmed by its own test.

This file closes that loop. It **never imports the generator.** Every marker,
separator and expected string below is a literal typed here; every figure is
recomputed from the artifact that produced it — ``eval/scorecards/``,
``eval/f1-report.json``, ``eval/skill-eval-workspace/iteration-3/``,
``skills/*/skill.usf.yaml``, ``scenarios/registry.yaml``, ``LICENSE``,
``NOTICE``, ``vendor/skill-judge/PROVENANCE.md`` — and compared against the text
actually committed to ``README.md``. The generator is exercised exactly once,
as a black box: ``--check`` must exit 0 on the committed state.

Two imports are not the generator and are deliberate:

* ``scripts.ship_floor.aggregate_verdict`` is *the ship gate itself*, the single
  definition of SHIP in this repository. Re-implementing its arithmetic here
  would create a second copy of a gate whose constants are frozen by ADR, which
  is worse than depending on it. Each verdict is cross-checked against the
  verdict the scorecard stores, so the gate and the artifact must agree too.
* ``validators.usf.validate_manifest_file`` is the USF validator the badge is a
  claim *about*. A hand-rolled schema check here would badge a different claim.
"""

from __future__ import annotations

import json
import re
import statistics
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.ship_floor import aggregate_verdict  # noqa: E402
from validators.usf import validate_manifest_file  # noqa: E402

README = REPO_ROOT / "README.md"
GENERATOR = REPO_ROOT / "scripts" / "generate_badges.py"

#: Typed here, not imported. If the generator's markers move, the row it thinks
#: it maintains and the row this file reads part company, and that is a failure.
BEGIN_MARKER = "<!-- BEGIN:badges — generated by scripts/generate_badges.py; do not hand-edit -->"
END_MARKER = "<!-- END:badges -->"

#: U+00B7 MIDDLE DOT. Typed as a literal so a changed separator constant inside
#: the generator cannot quietly redefine what this file expects to find.
DOT = "·"

#: `[![alt](shields url)](link)` — the only shape a badge in this row may take.
BADGE_RE = re.compile(
    r"\[!\[(?P<alt>[^\]]*)\]\((?P<img>https://img\.shields\.io/badge/[^)\s]+)\)\]\((?P<link>[^)\s]+)\)"
)

#: shields.io reads a single `-` as its field separator and doubles a literal one.
FIELD_SPLIT = re.compile(r"(?<!-)-(?!-)")


# --------------------------------------------------------------------------- #
# Reading the committed row
# --------------------------------------------------------------------------- #


def _readme() -> str:
    return README.read_text(encoding="utf-8")


def _badge_block(text: str | None = None) -> str:
    """The committed text between the badge markers, markers excluded."""
    text = _readme() if text is None else text
    start, end = text.find(BEGIN_MARKER), text.find(END_MARKER)
    assert start != -1 and end != -1 and start < end, "README.md has lost its badge markers"
    return text[start + len(BEGIN_MARKER) : end]


class ParsedBadge:
    """One badge as committed: decoded fields, colour, alt text and link."""

    def __init__(self, match: re.Match[str]) -> None:
        path = match.group("img").rsplit("/badge/", 1)[1]
        raw = FIELD_SPLIT.split(path)
        self.fields = [unquote(f).replace("--", "-").replace("__", "_") for f in raw[:-1]]
        self.colour = raw[-1]
        self.alt = match.group("alt")
        self.link = match.group("link")

    @property
    def label(self) -> str:
        return self.fields[0] if len(self.fields) == 2 else ""

    @property
    def message(self) -> str:
        return self.fields[-1]

    def __repr__(self) -> str:  # pragma: no cover - failure output only
        return f"<badge {self.label!r} {self.message!r} #{self.colour} -> {self.link}>"


def badges() -> list[ParsedBadge]:
    parsed = [ParsedBadge(m) for m in BADGE_RE.finditer(_badge_block())]
    assert parsed, "the badge block parsed to zero badges — the row shape changed"
    return parsed


def badge(label: str) -> ParsedBadge:
    for item in badges():
        if item.label == label:
            return item
    raise AssertionError(f"the badge row has no {label!r} badge; it has {[b.label for b in badges()]}")


def _run_check(readme: Path) -> subprocess.CompletedProcess[str]:
    """The generator as a BLACK BOX. No import, no shared interpreter state."""
    return subprocess.run(
        [sys.executable, str(GENERATOR), "--check", "--readme", str(readme)],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
    )


# --------------------------------------------------------------------------- #
# Independent derivations. Each reads the artifact, never a summary of it.
# --------------------------------------------------------------------------- #


def _skill_roster() -> list[str]:
    roster = sorted(p.name for p in (REPO_ROOT / "skills").iterdir() if (p / "SKILL.md").is_file())
    assert roster, "skills/ ships no SKILL.md; there is no roster to badge against"
    return roster


def _judged() -> tuple[int, int, float, int]:
    """``(shipped, roster, pooled_mean, pooled_n)`` recomputed over the scorecards."""
    roster = _skill_roster()
    shipped, judgments = 0, []
    for path in sorted((REPO_ROOT / "eval" / "scorecards").glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        skill = str(payload["skill"])
        assert skill in roster, f"{path.name} scores {skill!r}, which ships no SKILL.md"
        verdict, why = aggregate_verdict(skill, payload.get("aggregate"))
        assert verdict == payload["verdict"], (
            f"{path.name} stores verdict {payload['verdict']!r} but the gate recomputes {verdict!r} ({why})"
        )
        shipped += verdict == "SHIP"
        judgments += [float(j) for j in payload["aggregate"]["judgments"]]
    assert judgments, "eval/scorecards/ holds no judgments; there is no pooled mean to badge"
    return shipped, len(roster), round(statistics.fmean(judgments), 1), len(judgments)


def _f1_categories() -> dict[str, list[dict]]:
    report = json.loads((REPO_ROOT / "eval" / "f1-report.json").read_text(encoding="utf-8"))
    buckets: dict[str, list[dict]] = {"pass": [], "fail": [], "declared-and-uncovered": []}
    for row in report["categories"]:
        assert row["status"] in buckets, f"{row['category']}: unrecognised status {row['status']!r}"
        buckets[row["status"]].append(row)
    return buckets


def _f1_published_score() -> float:
    """The one scenario-level F1 shared by every category that publishes one.

    The pill leads with a SCORE now, so the score is recomputed from the report
    rather than read off the pill. If those categories ever stop agreeing on a
    single number there is no single number to show, and this says so before the
    badge quietly shows one of them.
    """
    scores = {row["scenario_level"]["f1"] for row in _f1_categories()["pass"]}
    assert len(scores) == 1, (
        f"the categories that publish an F1 no longer share one score {sorted(scores)}; "
        "the badge must not show a single number as if they did"
    )
    return scores.pop()


def _panel_size() -> int:
    """How many judges ``eval/scorecards/`` records, recomputed from the scorecards.

    The pill names the panel, so the panel size is a published figure like any
    other. Every scorecard must record the SAME roster and every judge in it must
    have actually returned a judgment — otherwise "the panel" is not one thing
    and the badge cannot name it with one number.
    """
    panels, judged = set(), set()
    for path in sorted((REPO_ROOT / "eval" / "scorecards").glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        panels.add(tuple(sorted(payload["providers"])))
        judged |= {str(j["provider"]) for j in payload["judgments"]}
    assert len(panels) == 1, f"the scorecards record more than one judge panel: {sorted(panels)}"
    roster = set(panels.pop())
    assert judged == roster, (
        f"the badge names a panel of {len(roster)}; the judges that actually returned scores are {sorted(judged)}"
    )
    return len(roster)


def _control_delta() -> tuple[float, float, float, int]:
    """``(delta, with_mean, without_mean, n)`` over the blind CONTROL arm of iteration-3 alone.

    The pill publishes the two ARMS and the alt text publishes the delta, so all
    three are recomputed here. A badge that took one arm from the control and the
    other from somewhere else would still read as a coherent pair.
    """
    payload = json.loads(
        (REPO_ROOT / "eval" / "skill-eval-workspace" / "iteration-3" / "benchmark.json").read_text(encoding="utf-8")
    )
    controls = [c for c in payload["cases"] if "-control-" in c["eval"]]
    assert controls, "iteration-3 ran no -control- case; there is no blind-control delta to badge"
    with_arm = statistics.fmean(float(c["with_skill"]["pass_rate"]) for c in controls)
    without_arm = statistics.fmean(float(c["without_skill"]["pass_rate"]) for c in controls)
    return round(with_arm - without_arm, 2), round(with_arm, 2), round(without_arm, 2), len(controls)


def _usf_conformant() -> tuple[int, int]:
    roster = _skill_roster()
    conformant = 0
    for name in roster:
        manifest = REPO_ROOT / "skills" / name / "skill.usf.yaml"
        if manifest.is_file() and validate_manifest_file(manifest).ok:
            conformant += 1
    return conformant, len(roster)


def _rubric_upstream() -> str:
    provenance = (REPO_ROOT / "vendor" / "skill-judge" / "PROVENANCE.md").read_text(encoding="utf-8")
    match = re.search(r"Upstream\s*\|\s*`([\w.-]+/[\w.-]+)`", provenance)
    assert match, "vendor/skill-judge/PROVENANCE.md records no `owner/repo` upstream to attribute"
    return match.group(1)


