def test_check_exits_zero_on_the_committed_state():
    result = _run_check(README)
    assert result.returncode == 0, f"README.md's badge row is out of date:\n{result.stdout}{result.stderr}"


#: (name, committed substring, replacement) — one entry per DERIVED figure in the
#: row. Every value a reader could act on has to appear here: a figure with no
#: mutation case is a figure nothing stops a maintainer from retyping.
MUTATIONS = [
    ("pooled mean", "111.3", "119.9"),
    ("ship count", "11%2F11%20SHIP", "12%2F12%20SHIP"),
    # The coverage count, the by-rule clause and the delta moved off their pills
    # into their alt text when the row was reworded. They are still derived, still
    # published and still mutable by hand, so they are still guarded here — the
    # literal moves with the figure, the case does not go away.
    ("F1 coverage", "7 of 10", "10 of 10"),
    ("F1 boundary clause", "3 publish none by rule", "0 publish none by rule"),
    ("control delta", "+0.52", "+0.90"),
    ("USF conformance", "11%2F11%20skills", "9%2F11%20skills"),
    ("scenario count", "62%20%C2%B7%20tiered", "58%20%C2%B7%20tiered"),
    ("licence id", "Apache--2.0", "MIT"),
    ("rubric upstream", _rubric_upstream().replace("-", "--").replace("/", "%2F"), "an--unrelated%2Frepository"),
    ("non-endorsement", "NOT%20an%20OWASP%20project", "An%20OWASP%20project"),
]


@pytest.mark.parametrize("name,committed,replacement", MUTATIONS, ids=[m[0] for m in MUTATIONS])
def test_a_hand_edited_badge_fails_the_check(tmp_path, name, committed, replacement):
    """The failure mode this file exists for: a figure typed by hand.

    Mutate one value, prove ``--check`` rejects it, prove regenerating restores
    exactly the committed bytes. A badge that survives this loop is unguarded.
    """
    original = _readme()
    assert committed in _badge_block(original), f"{committed!r} is no longer in the row; this case tests nothing"
    copy = tmp_path / "README.md"
    copy.write_text(original.replace(committed, replacement, 1), encoding="utf-8")

    assert _run_check(copy).returncode == 1, f"a hand-edited {name} passed --check"
    rewrite = subprocess.run(
        [sys.executable, str(GENERATOR), "--readme", str(copy)], capture_output=True, text=True, cwd=str(REPO_ROOT)
    )
    assert rewrite.returncode == 0, rewrite.stderr
    assert copy.read_text(encoding="utf-8") == original, f"regenerating did not restore the derived {name}"


def test_a_deleted_badge_fails_the_check(tmp_path):
    """Dropping a badge is drift too. The row cannot silently get shorter."""
    original = _readme()
    for target in badges():
        block = _badge_block(original)
        rendered = next(m.group(0) for m in BADGE_RE.finditer(block) if ParsedBadge(m).link == target.link)
        copy = tmp_path / "README.md"
        copy.write_text(original.replace(rendered, "", 1), encoding="utf-8")
        assert _run_check(copy).returncode == 1, f"deleting the {target.label or target.message!r} badge passed --check"


