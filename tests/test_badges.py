def test_every_number_the_row_shows_is_derived_from_something_in_this_repository():
    """No badge may carry a figure with no source.

    Every numeric token in every badge MESSAGE — the part a reader actually reads
    off the pill — is recomputed here from the artifact it came from. A number
    that appears in the row and in nothing else is, by definition, hand-typed.
    """
    shipped, roster, pooled_mean, _n = _judged()
    delta, with_rate, without_rate, _controls = _control_delta()
    conformant, usf_roster = _usf_conformant()
    registry = yaml.safe_load((REPO_ROOT / "scenarios" / "registry.yaml").read_text(encoding="utf-8"))
    buckets = _f1_categories()
    derived = {
        str(shipped),
        str(roster),
        f"{pooled_mean:g}",
        "120",  # the rubric's own scale, fixed by vendor/skill-judge/PROVENANCE.md
        str(_panel_size()),
        f"{_f1_published_score():.3f}",
        f"{delta:.2f}",
        f"{with_rate:.2f}",
        f"{without_rate:.2f}",
        str(conformant),
        str(usf_roster),
        str(len(registry["scenarios"])),
        str(len(buckets["pass"])),
        str(len(buckets["pass"]) + len(buckets["fail"]) + len(buckets["declared-and-uncovered"])),
        str(len(buckets["declared-and-uncovered"])),
        "2.0",  # the `2.0` of the SPDX identifier Apache-2.0, checked against LICENSE above
    }
    for item in badges():
        for token in re.findall(r"\d+(?:\.\d+)?", item.message):
            assert token in derived, f"badge {item.label or item.message!r} shows {token!r}, which nothing derives"


